// HandSilhouettePath.swift — the hand outline the gesture constellation draws.
//
// The legacy app shipped this as an SVG in an asset catalog, but `swift build`
// (the Mac dev shell) only COPIES a package `.xcassets` — it never runs
// `actool`, so `Image(_, bundle: .module)` would not resolve there. Rather than
// depend on an inconsistent asset pipeline, the outline is embedded as its raw
// SVG path data (viewBox 1000×729, fingers pointing right) and parsed into a
// SwiftUI `Path`. Portable everywhere, exact silhouette, no bundle lookup.

