    /// Parse the embedded absolute `M/L/C/Z` path, mapping viewBox coords into
    /// `rect`. Pixelmator emits explicit command letters, but implicit command
    /// repetition (a run of coordinate sets after one letter) is handled too.
    static func path(in rect: CGRect) -> Path {
        let sx = rect.width / viewBox.width
        let sy = rect.height / viewBox.height
        func p(_ x: CGFloat, _ y: CGFloat) -> CGPoint {
            CGPoint(x: rect.minX + x * sx, y: rect.minY + y * sy)
        }
        var path = Path()
        let tokens = pathData.split(separator: " ")
        var i = 0
        var cmd: Character = " "
        func num() -> CGFloat {
            defer { i += 1 }
            return i < tokens.count ? CGFloat(Double(tokens[i]) ?? 0) : 0
        }
        while i < tokens.count {
            let tok = tokens[i]
            if tok.count == 1, let c = tok.first, c.isLetter {
                cmd = c; i += 1
                if c == "Z" || c == "z" { path.closeSubpath(); continue }
            }
            switch cmd {
            case "M": path.move(to: p(num(), num()))
            case "L": path.addLine(to: p(num(), num()))
            case "C":
                let c1 = p(num(), num()); let c2 = p(num(), num()); let end = p(num(), num())
                path.addCurve(to: end, control1: c1, control2: c2)
            default: i += 1   // unknown — skip defensively
            }
        }
        return path
    }

